#!/usr/bin/env python3
"""gen_states.py - write port/wl_states.c, the table of every actor state.

Save games store an actor's state as an index into this table instead of a
pointer.  The table lists every global "statetype s_xxx = {...}" definition
in WL_AGENT.C and WL_ACT2.C, in source order, and copies the source's
#if/#ifdef/#else/#endif lines around them so the table holds exactly the
states that the current version (WL1, SPEAR, ...) compiles.

New entries must only ever be appended at the end of a file's list, or old
save games load the wrong states.  The version number in the save header
(port/wl_persist.h) has to change if that is ever unavoidable.

    scripts/gen_states.py > port/wl_states.c
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FILES = ["WOLFSRC/WL_AGENT.C", "WOLFSRC/WL_ACT2.C"]
DEF = re.compile(r"^\s*statetype\s+(s_\w+)\s*=")
COND = re.compile(r"^\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b")

out = sys.stdout
out.write("/*\n * wl_states.c - every actor state, for save games (WOLF-7).\n"
          " * GENERATED by scripts/gen_states.py from %s; do not edit.\n */\n\n"
          % " and ".join(f.split("/")[1] for f in FILES))
out.write('#include "WL_DEF.H"\n#include "wl_persist.h"\n\n')

names = []
body = []
for f in FILES:
    body.append("\t// %s\n" % f.split("/")[1])
    with open(os.path.join(ROOT, f), encoding="latin-1") as src:
        for line in src:
            m = DEF.match(line)
            if m:
                names.append(m.group(1))
                body.append("\t&%s,\n" % m.group(1))
            elif COND.match(line):
                body.append(line.strip() + "\n")

# the externs repeat the same conditionals so that every name is declared
for line in body:
    if line.startswith("\t&"):
        out.write("extern statetype %s;\n" % line.strip()[1:-1])
    elif line.startswith("#"):
        out.write(line)
out.write("\nstatetype *const wl_states[] =\n{\n")
for line in body:
    out.write(line)
out.write("};\n\nconst int wl_numstates = sizeof(wl_states) / sizeof(wl_states[0]);\n")
