#!/usr/bin/env python3
"""Turn the MakeOBJ data objects in WOLFSRC/OBJ (GAMEPAL.OBJ, SIGNON.OBJ) into C.

The DOS build linked these 16-bit OMF objects directly.  Each holds one public
symbol (e.g. _gamepal) followed by its bytes in LEDATA records.  We emit a C
array per symbol, named without the leading underscore, as `unsigned char`.
"""
import argparse
import pathlib
import struct
import sys


def read_index(buf, pos):
    if buf[pos] & 0x80:
        return ((buf[pos] & 0x7F) << 8) | buf[pos + 1], pos + 2
    return buf[pos], pos + 1


def parse(path):
    data = pathlib.Path(path).read_bytes()
    pos = 0
    pubs = []          # (name, segindex, offset)
    segs = {}          # segindex -> bytearray
    while pos < len(data):
        rtype = data[pos]
        rlen = struct.unpack_from('<H', data, pos + 1)[0]
        body = data[pos + 3:pos + 3 + rlen - 1]   # drop checksum byte
        pos += 3 + rlen
        if rtype in (0x90, 0x91):                  # PUBDEF
            p = 0
            _grp, p = read_index(body, p)
            seg, p = read_index(body, p)
            if seg == 0:
                p += 2
            wide = 4 if rtype == 0x91 else 2
            while p < len(body):
                n = body[p]
                name = body[p + 1:p + 1 + n].decode('ascii')
                p += 1 + n
                off = int.from_bytes(body[p:p + wide], 'little')
                p += wide
                _typ, p = read_index(body, p)
                pubs.append((name, seg, off))
        elif rtype in (0xA0, 0xA1):                # LEDATA
            p = 0
            seg, p = read_index(body, p)
            wide = 4 if rtype == 0xA1 else 2
            off = int.from_bytes(body[p:p + wide], 'little')
            p += wide
            chunk = body[p:]
            buf = segs.setdefault(seg, bytearray())
            if len(buf) < off + len(chunk):
                buf.extend(b'\0' * (off + len(chunk) - len(buf)))
            buf[off:off + len(chunk)] = chunk
        elif rtype in (0xA2, 0xA3):                # LIDATA: MakeOBJ never emits it
            sys.exit(f'{path}: LIDATA records are not supported')
        elif rtype in (0x8A, 0x8B):                # MODEND
            break
    if len(pubs) != 1:
        sys.exit(f'{path}: expected exactly one public symbol, got {pubs}')
    name, seg, off = pubs[0]
    return name.lstrip('_'), bytes(segs[seg][off:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', '--output', required=True)
    ap.add_argument('objects', nargs='+')
    args = ap.parse_args()
    out = ['/* Generated by scripts/obj2c.py from WOLFSRC/OBJ - do not edit. */', '']
    for obj in args.objects:
        name, blob = parse(obj)
        out.append(f'/* {pathlib.Path(obj).name}: {len(blob)} bytes */')
        out.append(f'unsigned char {name}[{len(blob)}] = {{')
        for i in range(0, len(blob), 16):
            out.append('\t' + ','.join(str(b) for b in blob[i:i + 16]) + ',')
        out.append('};')
        out.append('')
    pathlib.Path(args.output).write_text('\n'.join(out))


if __name__ == '__main__':
    main()
