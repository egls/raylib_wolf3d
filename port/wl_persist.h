/*
 * wl_persist.h - where config and save files live, and explicit
 * little-endian, fixed-size serialization for them (WOLF-7).
 *
 * The DOS code wrote CONFIG.WL1 and SAVEGAM?.WL1 by dumping structs and
 * pointers to disk.  Those dumps depend on the compiler's int size,
 * padding and the addresses of the program's data, so they are replaced
 * by field-by-field writes: every number has a fixed width and byte order,
 * pointers become indices, and each file starts with a magic and version.
 */
#ifndef WL_PERSIST_H
#define WL_PERSIST_H

#include <stddef.h>
#include <stdint.h>

/*
 * On Windows, config and saves go to %APPDATA%/raylib_wolf3d/
 * (LOCALAPPDATA is the fallback). On Linux they go to
 * $XDG_CONFIG_HOME/raylib_wolf3d/, or
 * ~/.config/raylib_wolf3d/ when XDG_CONFIG_HOME is unset (the directory is
 * created on first use).  Returns the full path of `name` there, in a
 * static buffer that the next call overwrites.
 */
const char	*WL_UserFile (const char *name);

/* A growable byte buffer with a read cursor.  Reads past the end return 0
 * and set `bad`, so a parser can read everything and check once. */
typedef struct
{
	uint8_t	*buf;
	size_t	len, cap, pos;
	int		bad;
} wl_stream;

void		WS_Init (wl_stream *s);
void		WS_Free (wl_stream *s);
void		WS_W8 (wl_stream *s, uint32_t v);
void		WS_W16 (wl_stream *s, uint32_t v);
void		WS_W32 (wl_stream *s, uint32_t v);
void		WS_WBytes (wl_stream *s, const void *p, size_t n);
uint32_t	WS_R8 (wl_stream *s);
uint32_t	WS_R16 (wl_stream *s);
uint32_t	WS_R32 (wl_stream *s);
void		WS_RBytes (wl_stream *s, void *p, size_t n);
#define		WS_RS16(s)	((int16_t)WS_R16(s))
#define		WS_RS32(s)	((int32_t)WS_R32(s))

int			WS_WriteFile (int fd, const wl_stream *s);	// 1 on success
int			WS_ReadFile (int fd, wl_stream *s);			// rest of fd; 1 on success
uint32_t	WS_Checksum (const wl_stream *s, size_t from, size_t to);

/* Actor states by index (port/wl_states.c, generated by scripts/gen_states.py). */
struct statestruct;
extern struct statestruct *const	wl_states[];
extern const int					wl_numstates;
int					WL_StateIndex (const struct statestruct *state);	// -1 if NULL, Quit()s if unknown
struct statestruct	*WL_StateFromIndex (int index);					// NULL if out of range

/* File formats */
#define WL_CONFIG_MAGIC		"RLW3DCFG"
#define WL_CONFIG_VERSION	1
#define WL_SAVE_MAGIC		"RLW3DSAV"
#define WL_SAVE_VERSION		1

#endif
